#!/usr/bin/env python3
"""Generate a versioned static Unicode property table for the Latent lexer.

This tool emits data only. Runtime range lookup and character classification
remain implemented in bootstrap/unicode_tables.lt. Run once under each
supported CPython Unicode database version (currently 14.0.0 and 15.0.0).
"""
from __future__ import annotations

import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def property_ranges(predicate):
    result = []
    start = None
    previous = None
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start is None:
                start = previous = codepoint
            elif codepoint == previous + 1:
                previous = codepoint
            else:
                result.append((start, previous))
                start = previous = codepoint
        elif start is not None:
            result.append((start, previous))
            start = previous = None
    if start is not None:
        result.append((start, previous))
    return result


def latent_string(value: str) -> str:
    escaped = []
    for character in value:
        escaped.append({
            "\\": "\\\\",
            '"': '\\"',
            "\n": "\\n",
            "\r": "\\r",
            "\t": "\\t",
            "\0": "\\0",
        }.get(character, character))
    return '"' + "".join(escaped) + '"'


def emit_ranges(name: str, intervals: list[tuple[int, int]]) -> list[str]:
    values = ", ".join(
        f"[{latent_string(chr(start))}, {latent_string(chr(end))}]"
        for start, end in intervals
    )
    return [f"{name} = [{values}]"]


def decimal_blocks() -> list[str]:
    intervals = property_ranges(str.isdecimal)
    blocks = []
    for start, end in intervals:
        length = end - start + 1
        if length % 10:
            raise RuntimeError(
                f"decimal interval is not a multiple of ten: U+{start:04X}-U+{end:04X}"
            )
        for offset in range(0, length, 10):
            blocks.append("".join(chr(start + offset + digit) for digit in range(10)))
    return blocks


def error_repr_map() -> list[tuple[str, str]]:
    codepoints = set(range(0x20)) | set(range(0x7F, 0xA0))
    codepoints.update(
        codepoint for codepoint in range(0x110000)
        if chr(codepoint).isspace()
    )
    return [(chr(codepoint), repr(chr(codepoint))) for codepoint in sorted(codepoints)]


def main() -> None:
    version = unicodedata.unidata_version
    suffix = version.replace(".", "_")
    output = ROOT / "bootstrap" / f"unicode_data_{suffix}.lt"
    alpha = property_ranges(str.isalpha)
    numeric_tail = property_ranges(
        lambda character: character.isalnum() and not character.isalpha()
    )
    digits = property_ranges(str.isdigit)
    whitespace = property_ranges(str.isspace)
    blocks = decimal_blocks()
    error_reprs = error_repr_map()

    lines = [
        f"# Static Unicode {version} property data for the P15 M3 lexer.",
        "# Generated by tools/generate_bootstrap_unicode_tables.py.",
        "# All classification and range-search algorithms are in Latent code.",
        f'UNICODE_VERSION = "{version}"',
        "",
    ]
    lines += emit_ranges("ALPHA_RANGES", alpha)
    lines += [""]
    lines += emit_ranges("NUMERIC_TAIL_RANGES", numeric_tail)
    lines += [""]
    lines += emit_ranges("DIGIT_RANGES", digits)
    lines += [
        "",
        "DECIMAL_DIGIT_BLOCKS = ["
        + ", ".join(latent_string(block) for block in blocks)
        + "]",
        "",
    ]
    lines += emit_ranges("WHITESPACE_RANGES", whitespace)
    lines += [
        "",
        "ERROR_REPR_MAP = ["
        + ", ".join(
            f"[{latent_string(character)}, {latent_string(representation)}]"
            for character, representation in error_reprs
        )
        + "]",
    ]
    lines.append("")
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"wrote {output}: Unicode {version}, alpha={len(alpha)}, "
        f"numeric-tail={len(numeric_tail)}, digit={len(digits)}, "
        f"decimal-blocks={len(blocks)}, whitespace={len(whitespace)}, "
        f"error-reprs={len(error_reprs)}"
    )


if __name__ == "__main__":
    main()
